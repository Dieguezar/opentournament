const catalogs: Record<Locale, Record<ApiErrorCode, string>> = {
  en: englishMessages,
  es: spanishMessages,
};

export function getApiErrorMessage(code: string, locale: Locale, serverMessage?: string): string {
  const localizedMessage = catalogs[locale][code as ApiErrorCode];
  if (localizedMessage) return localizedMessage;
  if (locale === 'en' && serverMessage?.trim()) return serverMessage;
  return locale === 'es' ? 'No se pudo completar la acción.' : 'The action could not be completed.';
}
